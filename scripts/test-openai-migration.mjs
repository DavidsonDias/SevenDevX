import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const env = new Map();
globalThis.Deno = { env: { get: name => env.get(name) } };
const { openAIRequest, textModel, imageModel } = await import('../supabase/functions/_shared/openai.ts');
let calls = 0;
globalThis.fetch = async (url, init) => {
  calls++;
  assert.equal(url, 'https://api.openai.com/v1/chat/completions');
  assert.equal(init.headers.get('Authorization'), 'Bearer offline-test');
  assert.deepEqual(JSON.parse(init.body), { messages: [{ role: 'user', content: 'test' }], stream: true, tools: [] });
  assert.ok(init.signal instanceof AbortSignal);
  return new Response('data: [DONE]\n\n', { status: 429, headers: { 'content-type': 'text/event-stream' } });
};
await assert.rejects(openAIRequest('chat/completions'), /not configured/);
assert.equal(calls, 0);
env.set('OPENAI_API_KEY', ' offline-test ');
const result = await openAIRequest('chat/completions', { method: 'POST', body: JSON.stringify({ messages: [{ role: 'user', content: 'test' }], stream: true, tools: [] }) });
assert.equal(result.status, 429);
assert.equal(await result.text(), 'data: [DONE]\n\n');
assert.equal(textModel(), 'gpt-4.1-mini');
assert.equal(imageModel(), 'gpt-image-1.5');
env.set('OPENAI_TEXT_MODEL', ' configured-model ');
assert.equal(textModel(), 'configured-model');
const logo = await readFile(new URL('../supabase/functions/logo-variations-ai/index.ts', import.meta.url), 'utf8');
assert.ok(logo.includes("openAIRequest('images/generations'"));
assert.ok(logo.includes('b64_json'));
assert.ok(!logo.includes('modalities:'));
console.log('PASS: missing key blocks requests; authorization, streaming body and provider errors preserved; model configuration and image contract verified. No external requests.');
